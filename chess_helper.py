def round_rect(c, x1, y1, x2, y2, r, **kw):
    pts = [x1 + r, y1, x2 - r, y1, x2, y1, x2, y1 + r, x2, y2 - r, x2, y2,
           x2 - r, y2, x1 + r, y2, x1, y2, x1, y2 - r, x1, y1 + r, x1, y1]
    return c.create_polygon(pts, smooth=True, outline="", **kw)


class FancyButton(tk.Canvas):
    """Orange button, slightly rounded, light top edge and darker bottom edge (shadow)."""

    RADIUS = 6
    HEIGHT = 34

    def __init__(self, master, text, command):
        text = text.upper()
        self.font = tkfont.Font(family="Segoe UI", size=11, weight="bold")
        super().__init__(master, width=self.font.measure(text) + 28, height=self.HEIGHT,
                         bg=BG, highlightthickness=0, bd=0, cursor="hand2")
        self.text, self.command = text, command
        self.hover = self.pressed = False
        self.bind("<Configure>", lambda e: self.redraw())
        self.bind("<Enter>", lambda e: self._set(hover=True))
        self.bind("<Leave>", lambda e: self._set(hover=False, pressed=False))
        self.bind("<ButtonPress-1>", lambda e: self._set(pressed=True))
        self.bind("<ButtonRelease-1>", self._release)

    def _set(self, **kw):
        for k, v in kw.items():
            setattr(self, k, v)
        self.redraw()

    def _release(self, e):
        was_pressed = self.pressed
        self._set(pressed=False)
        if was_pressed and 0 <= e.x < self.winfo_width() and 0 <= e.y < self.winfo_height():
            self.command()

    def redraw(self):
        self.delete("all")
        w, h, r = max(self.winfo_width(), 2) - 1, self.HEIGHT - 1, self.RADIUS
        top, bottom = (5, 1) if self.pressed else (2, 4)
        round_rect(self, 0, 0, w, h, r, fill=BTN_LO)
        round_rect(self, 0, 0, w, h - bottom, r, fill=BTN_LO if self.pressed else BTN_HI)
        round_rect(self, 0, top, w, h - bottom, r, fill=BTN_HOVER if self.hover else BTN)
        cx, cy = w / 2, (top + h - bottom) / 2   # centre of the button face
        self.create_text(cx, cy, text=self.text, fill=BTN_TEXT, font=self.font, anchor="center")


class InfoBox(tk.Canvas):
    """Message box with the same rounded orange frame as the board."""

    BW, PAD = 5, 10

    def __init__(self, master, text=""):
        super().__init__(master, bg=BG, highlightthickness=0, bd=0, height=60)
        self.text, self._h = text, 0
        self.font = tkfont.Font(family="Consolas", size=10, weight="bold")
        self.bind("<Configure>", lambda e: self.redraw())

    def set(self, text):
        self.text = text
        self.redraw()

    def redraw(self):
        w = max(self.winfo_width(), 80) - 1
        bw, pad = self.BW, self.PAD
        self.delete("all")
        t = self.create_text(w / 2, bw + pad, text=self.text, anchor="n", justify="center",
                             fill=FG, font=self.font, width=max(w - 2 * (bw + pad), 40))
        box = self.bbox(t)
        th = max((box[3] - box[1]) if box else 0, self.font.metrics("linespace"))
        h = th + 2 * (bw + pad)
        edge = max(2, bw // 3)
        round_rect(self, 0, 0, w, h, 9, fill=BTN_LO)                              # darker bottom edge
        round_rect(self, 0, 0, w, h - edge, 9, fill=BTN_HI)                       # lighter top edge
        round_rect(self, 0, max(1, edge // 2), w, h - edge, 9, fill=BTN)          # frame body
        round_rect(self, bw, bw, w - bw, h - bw, 5, fill=FIELD)                   # inner dark panel
        self.tag_raise(t)
        if h + 1 != self._h:
            self._h = h + 1
            self.configure(height=self._h)


class Header(tk.Canvas):
    """Logo + wordmark, scaled so together they fill the window width."""

    GAP, PAD = 14, 8

    def __init__(self, master, root):
        super().__init__(master, bg=BG, highlightthickness=0, bd=0, height=70)
        self.root, self._job, self._h = root, None, 0
        self.logo_img = self.word_img = self.icon = None
        if Image:
            self.logo_src = Image.open(io.BytesIO(base64.b64decode(LOGO_B64))).convert("RGB")
            self.word_src = Image.open(io.BytesIO(base64.b64decode(WORDMARK_B64))).convert("RGB")
            try:
                small = self.logo_src.resize((48, round(48 * self.logo_src.height / self.logo_src.width)))
                self.icon = ImageTk.PhotoImage(small)
                root.iconphoto(True, self.icon)
            except tk.TclError:
                pass
        else:  # no Pillow: show fixed-size images
            self.logo_img = tk.PhotoImage(data=LOGO_B64).subsample(3)
            self.word_img = tk.PhotoImage(data=WORDMARK_B64).subsample(2)
        self.bind("<Configure>", self._schedule)

    def _schedule(self, e):
        if self._job:
            self.after_cancel(self._job)
        self._job = self.after(50, self.render, e.width)

    def render(self, width):
        self._job = None
        self.delete("all")
        if Image:
            lw0, lh0 = self.logo_src.size
            ww0, wh0 = self.word_src.size
            avail = max(width - 2 * self.PAD - self.GAP, 100)
            h = avail / (lw0 / lh0 + ww0 / wh0)
            cap = max(48, int(self.root.winfo_height() * 0.2))
            h = int(max(32, min(h, cap)))
            lw, ww = round(lw0 * h / lh0), round(ww0 * h / wh0)
            self.logo_img = ImageTk.PhotoImage(self.logo_src.resize((lw, h), Image.LANCZOS))
            self.word_img = ImageTk.PhotoImage(self.word_src.resize((ww, h), Image.LANCZOS))
        else:
            lw, ww, h = self.logo_img.width(), self.word_img.width(), self.logo_img.height()
        x0 = max((width - (lw + self.GAP + ww)) // 2, 0)
        self.create_image(x0, self.PAD, image=self.logo_img, anchor="nw")
        self.create_image(x0 + lw + self.GAP, self.PAD + (h - self.word_img.height()) // 2,
                          image=self.word_img, anchor="nw")
        if h + 2 * self.PAD != self._h:
            self._h = h + 2 * self.PAD
            self.configure(height=self._h)


