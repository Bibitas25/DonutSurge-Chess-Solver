GLYPH = {"P": "\u265f", "N": "\u265e", "B": "\u265d", "R": "\u265c", "Q": "\u265b", "K": "\u265a"}


def app_dir():
    if getattr(sys, "frozen", False):
        return os.path.dirname(sys.executable)
    return os.path.dirname(os.path.abspath(__file__))


def is_valid_engine(path):
    """True if path looks like a runnable engine (on Windows: a real .exe, not a .zip/folder)."""
    if not path or not os.path.isfile(path):
        return False
    if path.lower().endswith((".zip", ".7z", ".tar", ".gz", ".txt", ".md", ".py", ".pdf")):
        return False
    if os.name == "nt":
        try:
            with open(path, "rb") as f:
                return path.lower().endswith(".exe") and f.read(2) == b"MZ"
        except OSError:
            return False
    return True


ENGINE_CONFIG = os.path.join(app_dir(), "chess_helper_engine.txt")


def load_saved_engine():
    try:
        with open(ENGINE_CONFIG, encoding="utf-8") as f:
            path = f.read().strip()
    except OSError:
        return None
    return path if is_valid_engine(path) else None


def save_engine(path):
    try:
        with open(ENGINE_CONFIG, "w", encoding="utf-8") as f:
            f.write(path)
    except OSError:
        pass


def find_engine():
    saved = load_saved_engine()
    if saved:
        return saved
    for folder in (app_dir(), os.getcwd()):
        for depth in ("", "*", os.path.join("*", "*")):
            for p in sorted(glob.glob(os.path.join(folder, depth, "*stockfish*"))):
                if is_valid_engine(p):
                    return p
    return None


