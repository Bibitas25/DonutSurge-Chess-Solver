    # ---------- drawing ----------
    def on_resize(self, e):
        side = min(e.width, e.height)
        self.bw = max(5, side // 80)   # frame thickness
        self.sh = max(3, side // 120)  # shadow offset
        self.sq = max(16, (side - 2 * self.bw - self.sh) // 8)
        total = 8 * self.sq + 2 * self.bw + self.sh
        self.ox = (e.width - total) // 2 + self.bw
        self.oy = (e.height - total) // 2 + self.bw
        self.draw()

    def xy(self, sq):
        f, r = chess.square_file(sq), chess.square_rank(sq)
        if self.flipped:
            return self.ox + (7 - f) * self.sq, self.oy + r * self.sq
        return self.ox + f * self.sq, self.oy + (7 - r) * self.sq

    def draw(self):
        c, S = self.canvas, self.sq
        c.delete("all")
        b, sh = self.bw, self.sh
        x1, y1, x2, y2 = self.ox - b, self.oy - b, self.ox + 8 * S + b, self.oy + 8 * S + b
        rad, edge = max(6, int(b * 1.3)), max(2, b // 3)
        round_rect(c, x1 + sh, y1 + sh, x2 + sh, y2 + sh, rad, fill=SHADOW)   # drop shadow
        round_rect(c, x1, y1, x2, y2, rad, fill=BTN_LO)                        # darker bottom edge
        round_rect(c, x1, y1, x2, y2 - edge, rad, fill=BTN_HI)                 # lighter top edge
        round_rect(c, x1, y1 + max(1, edge // 2), x2, y2 - edge, rad, fill=BTN)  # frame body
        for sq in chess.SQUARES:
            x, y = self.xy(sq)
            light = (chess.square_file(sq) + chess.square_rank(sq)) % 2 == 1
            color = LIGHT if light else DARK
            if sq == self.selected:
                color = SEL
            c.create_rectangle(x, y, x + S, y + S, fill=color, outline=color)
        if self.selected is not None:
            r = S * 0.13
            for m in self.board.legal_moves:
                if m.from_square == self.selected:
                    x, y = self.xy(m.to_square)
                    c.create_oval(x + S / 2 - r, y + S / 2 - r, x + S / 2 + r, y + S / 2 + r,
                                  fill=HINT, outline="")
        font = ("Segoe UI Symbol", max(10, int(S * 0.56)))
        o = max(1, round(S / 50))
        for sq, p in self.board.piece_map().items():
            x, y = self.xy(sq)
            g = GLYPH[p.symbol().upper()]
            fill, edge = ("white", "black") if p.color else ("black", "white")
            for dx, dy in ((-o, 0), (o, 0), (0, -o), (0, o)):
                c.create_text(x + S / 2 + dx, y + S / 2 + dy, text=g, font=font, fill=edge)
            c.create_text(x + S / 2, y + S / 2, text=g, font=font, fill=fill)
        if self.best:
            x1, y1 = self.xy(self.best.from_square)
            x2, y2 = self.xy(self.best.to_square)
            c.create_line(x1 + S / 2, y1 + S / 2, x2 + S / 2, y2 + S / 2, fill=HINT,
                          width=max(3, int(S * 0.11)), arrow=tk.LAST,
                          arrowshape=(S * 0.28, S * 0.31, S * 0.12))

    # ---------- interaction ----------
    def on_click(self, e):
        f, r = (e.x - self.ox) // self.sq, (e.y - self.oy) // self.sq
        if not (0 <= f < 8 and 0 <= r < 8):
            return
        sq = chess.square(7 - f, r) if self.flipped else chess.square(f, 7 - r)
        if self.busy:
            return
        self.best = None
        if self.selected is None:
            p = self.board.piece_at(sq)
            if p and p.color == self.board.turn:
                self.selected = sq
        else:
            move = chess.Move(self.selected, sq)
            p = self.board.piece_at(self.selected)
            if p and p.piece_type == chess.PAWN and chess.square_rank(sq) in (0, 7):
                move.promotion = chess.QUEEN
            if move in self.board.legal_moves:
                self.board.push(move)
                self.selected = None
                self.draw()
                return
            else:
                q = self.board.piece_at(sq)
                self.selected = sq if (q and q.color == self.board.turn) else None
        self.draw()

    def undo(self):
        if self.busy:
            return
        if self.board.move_stack:
            self.board.pop()
        self.selected = self.best = None
        self.draw()

    def flip(self):
        self.flipped = not self.flipped
        self.draw()

    def reset(self):
        if self.busy:
            return
        self.board = chess.Board()
        self.selected = self.best = None
        self.draw()

    def ensure_engine(self):
        if is_valid_engine(self.engine_path):
            return True
        self.engine_path = None
        messagebox.showinfo("ENGINE NEEDED",
                            "NO STOCKFISH ENGINE FOUND.\n\nDOWNLOAD IT FROM STOCKFISHCHESS.ORG (WINDOWS), UNZIP IT, "
                            "THEN SELECT THE STOCKFISH .EXE FILE ON THE NEXT SCREEN. "
                            "THE PROGRAM REMEMBERS YOUR CHOICE.")
        self.pick_engine()
        return bool(self.engine_path)

    # ---------- engine ----------
    def pick_engine(self):
        path = filedialog.askopenfilename(title="SELECT STOCKFISH EXECUTABLE",
                                          filetypes=[("PROGRAMS", "*.exe"), ("ALL FILES", "*.*")])
        if not path:
            return
        if not is_valid_engine(path):
            messagebox.showerror("ENGINE ERROR", BAD_ENGINE_MSG.upper())
            return
        self.engine_path = path
        save_engine(path)
        self.close_engine()

    def close_engine(self):
        if self.engine:
            try:
                self.engine.quit()
            except Exception:
                pass
            self.engine = None

    def analyse(self):
        if self.busy:
            return
        if not self.ensure_engine():
            return
        if self.board.is_game_over():
            self.out.set("GAME OVER: " + self.board.result())
            return
        self.busy = True
        self.out.set("THINKING...")
        board = self.board.copy()
        secs, lines = THINK_SECONDS, LINES
        threading.Thread(target=self.worker, args=(board, secs, lines), daemon=True).start()

    def worker(self, board, secs, lines):
        try:
            if self.engine is None:
                self.engine = chess.engine.SimpleEngine.popen_uci(self.engine_path)
            if "UCI_LimitStrength" in self.engine.options:
                self.engine.configure({"UCI_LimitStrength": False})
            infos = self.engine.analyse(board, chess.engine.Limit(time=secs), multipv=lines)
            rows, best = [], None
            for i, info in enumerate(infos):
                pv = info.get("pv", [])
                if not pv:
                    continue
                if i == 0:
                    best = pv[0]
                sc = info["score"].pov(board.turn)
                if sc.is_mate():
                    s = f"M{sc.mate()}"
                else:
                    s = f"{sc.score() / 100:+.2f}"
                san, b = [], board.copy()
                for m in pv[:6]:
                    san.append(b.san(m))
                    b.push(m)
                rows.append(f"{i + 1}. {s:>7}  {' '.join(san)}")
            text = "\n".join(rows)
            self.root.after(0, self.done, text, best)
        except OSError as ex:
            self.engine = None
            if getattr(ex, "winerror", None) == 193:
                self.engine_path = None
                msg = "ENGINE ERROR: " + BAD_ENGINE_MSG.replace("\n\n", " ").upper()
            else:
                msg = f"ENGINE ERROR: {ex}".upper()
            self.root.after(0, self.done, msg, None)
        except Exception as ex:
            self.engine = None
            self.root.after(0, self.done, f"ENGINE ERROR: {ex}".upper(), None)

    def done(self, text, best):
        self.busy = False
        self.best = best
        self.out.set(text)
        self.draw()

    def close(self):
        self.close_engine()
        self.root.destroy()


